# Writes the Rust constants the Groth16 spike contract needs, in NEAR's alt_bn128 byte layout (each number 32 bytes
# little-endian; a G2 point as x real, x imaginary, y real, y imaginary). The verifying key numbers are read from RISC
# Zero's own verifier source (risc0-groth16 3.0.5, src/verifier.rs), and the control root and BN254 control id from the
# JSON that `skarbnik-host groth16-args` writes (RISC Zero's default verifier parameters).
# Usage: python3 -I scripts/gen_groth16_vk.py <risc0-groth16-3.0.5/src/verifier.rs> <args.json> > verifier/groth16-near/src/vk.rs
import json, re, sys

src = open(sys.argv[1]).read()
params = json.load(open(sys.argv[2]))
num = {k: int(v) for k, v in re.findall(r'const (\w+): &str =\s*"(\d+)";', src)}

def le(n):
    return n.to_bytes(32, "little")

def g1(x, y):
    return le(num[x]) + le(num[y])

# risc0-groth16 builds a G2 point from [[X1, X2], [Y1, Y2]] with X2 and Y2 as the real parts (lib.rs, g2_from_bytes).
def g2(x1, x2, y1, y2):
    return le(num[x2]) + le(num[x1]) + le(num[y2]) + le(num[y1])

def const(name, data, comment):
    return f"/// {comment}\npub const {name}: [u8; {len(data)}] = {list(data)};\n"

out = ["// Generated by scripts/gen_groth16_vk.py from RISC Zero's Groth16 verifying key and verifier parameters.",
       "// Do not edit by hand. Byte layout: NEAR alt_bn128 (32 byte little-endian numbers).", ""]
out.append(const("ALPHA_G1", g1("ALPHA_X", "ALPHA_Y"), "Verifying key alpha (G1)."))
out.append(const("BETA_G2", g2("BETA_X1", "BETA_X2", "BETA_Y1", "BETA_Y2"), "Verifying key beta (G2)."))
out.append(const("GAMMA_G2", g2("GAMMA_X1", "GAMMA_X2", "GAMMA_Y1", "GAMMA_Y2"), "Verifying key gamma (G2)."))
out.append(const("DELTA_G2", g2("DELTA_X1", "DELTA_X2", "DELTA_Y1", "DELTA_Y2"), "Verifying key delta (G2)."))
ic = b"".join(g1(f"IC{i}_X", f"IC{i}_Y") for i in range(6))
out.append(const("IC", ic, "Verifying key IC0 to IC5 (G1), 64 bytes each."))
out.append(const("CONTROL_ROOT", bytes.fromhex(params["control_root"]), "RISC Zero's control root (risc0-zkvm 3.0.6 default)."))
out.append(const("BN254_CONTROL_ID", bytes.fromhex(params["bn254_control_id"]), "RISC Zero's BN254 identity control id (risc0-zkvm 3.0.6 default)."))
print("\n".join(out))
