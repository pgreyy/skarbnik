//! Spike S6b: a NEAR contract that checks a RISC Zero Groth16 proof itself, with NEAR's alt_bn128 host functions.
//! Not the bounty contract and not connected to any payout. One method, `verify_groth16(seal, image_id, journal)`,
//! returns true only if the proof shows that the program with that image id ran and wrote that journal.
//!
//! It follows RISC Zero's own verifier (risc0-groth16 3.0.5 `src/verifier.rs`, risc0-zkvm 3.0.6
//! `src/claim/receipt.rs`): the claim digest of a normal successful run is computed from the image id and the
//! journal; the five public numbers are the control root and the claim digest (each split into two 128 bit halves)
//! and the BN254 control id; the Groth16 check is e(-A, B) * e(alpha, beta) * e(vk_x, gamma) * e(C, delta) == 1,
//! with vk_x = IC0 + sum of input_i * IC_i. The fixed values are in `vk.rs` (generated by scripts/gen_groth16_vk.py).
use near_sdk::{env, log, near};

mod vk;

#[near(contract_state)]
#[derive(Default)]
pub struct Groth16Spike {}

fn hex(s: &str, what: &str) -> Vec<u8> {
    let s = s.trim();
    if s.len() % 2 != 0 {
        env::panic_str(&format!("{what}: odd hex length"));
    }
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap_or_else(|_| env::panic_str(&format!("{what}: not hex"))))
        .collect()
}

/// RISC Zero's tagged struct hash (risc0-binfmt 3.0.5 `src/hash.rs`, `tagged_struct`).
fn tagged(tag: &str, down: &[&[u8]], data: &[u32]) -> Vec<u8> {
    let mut all = env::sha256(tag.as_bytes());
    for d in down {
        all.extend_from_slice(d);
    }
    for w in data {
        all.extend_from_slice(&w.to_le_bytes());
    }
    all.extend_from_slice(&(down.len() as u16).to_le_bytes());
    env::sha256(&all)
}

/// Digest of `ReceiptClaim::ok(image_id, journal)`: no input, halted with exit code 0, no assumptions.
fn claim_digest(image_id: &[u8], journal: &[u8]) -> Vec<u8> {
    let zero = [0u8; 32];
    let post = tagged("risc0.SystemState", &[&zero], &[0]);
    let output = tagged("risc0.Output", &[&env::sha256(journal), &zero], &[]);
    tagged("risc0.ReceiptClaim", &[&zero, image_id, &post, &output], &[0, 0])
}

/// One 128 bit half of a digest as a 32 byte little-endian scalar (risc0-groth16 `split_digest`).
fn half(d: &[u8], i: usize) -> [u8; 32] {
    let mut s = [0u8; 32];
    s[..16].copy_from_slice(&d[16 * i..16 * i + 16]);
    s
}

/// A 32 byte big-endian number from the seal, as little-endian.
fn rev(b: &[u8]) -> Vec<u8> {
    b.iter().rev().copied().collect()
}

#[near]
impl Groth16Spike {
    /// Checks a 256 byte Groth16 seal (hex) for the given image id (64 hex) and journal (hex). Returns true or false;
    /// a seal whose numbers are not valid curve points makes the host function stop the call with an error.
    pub fn verify_groth16(&self, seal: String, image_id: String, journal: String) -> bool {
        let seal = hex(&seal, "seal");
        let image_id = hex(&image_id, "image_id");
        let journal = hex(&journal, "journal");
        if seal.len() != 256 || image_id.len() != 32 {
            env::panic_str("seal must be 256 bytes and image_id 32 bytes");
        }
        let g0 = env::used_gas().as_gas();

        // The five public numbers.
        let claim = claim_digest(&image_id, &journal);
        let inputs = [half(&vk::CONTROL_ROOT, 0), half(&vk::CONTROL_ROOT, 1), half(&claim, 0), half(&claim, 1), vk::BN254_CONTROL_ID];
        let g1 = env::used_gas().as_gas();

        // vk_x = IC0 + sum input_i * IC_(i+1): one multiexp over five items, then add IC0.
        let mut msm = Vec::with_capacity(5 * 96);
        for (i, s) in inputs.iter().enumerate() {
            msm.extend_from_slice(&vk::IC[64 * (i + 1)..64 * (i + 2)]);
            msm.extend_from_slice(s);
        }
        let sum = env::alt_bn128_g1_multiexp(&msm);
        let mut add = vec![0u8];
        add.extend_from_slice(&vk::IC[..64]);
        add.push(0);
        add.extend_from_slice(&sum);
        let vk_x = env::alt_bn128_g1_sum(&add);
        let g2 = env::used_gas().as_gas();

        // The proof points, from RISC Zero's big-endian seal (risc0-groth16 `Seal::decode`, `g1_from_bytes`,
        // `g2_from_bytes`). B is stored imaginary part first; NEAR wants the real part first.
        let a = [rev(&seal[0..32]), rev(&seal[32..64])].concat();
        let b = [rev(&seal[96..128]), rev(&seal[64..96]), rev(&seal[160..192]), rev(&seal[128..160])].concat();
        let c = [rev(&seal[192..224]), rev(&seal[224..256])].concat();
        let mut neg = vec![1u8];
        neg.extend_from_slice(&a);
        let neg_a = env::alt_bn128_g1_sum(&neg);

        let mut pairs = Vec::with_capacity(4 * 192);
        for (p, q) in [(&neg_a[..], &b[..]), (&vk::ALPHA_G1[..], &vk::BETA_G2[..]), (&vk_x[..], &vk::GAMMA_G2[..]), (&c[..], &vk::DELTA_G2[..])] {
            pairs.extend_from_slice(p);
            pairs.extend_from_slice(q);
        }
        let ok = env::alt_bn128_pairing_check(&pairs);
        let g3 = env::used_gas().as_gas();
        log!(
            "groth16 check: {}; gas (Tgas): claim digest {:.3}, inputs multiexp and sum {:.3}, pairing check {:.3}, total so far {:.3}",
            if ok { "ACCEPTED" } else { "REJECTED" },
            (g1 - g0) as f64 / 1e12,
            (g2 - g1) as f64 / 1e12,
            (g3 - g2) as f64 / 1e12,
            g3 as f64 / 1e12
        );
        ok
    }
}

