//! Level 2: checks a RISC Zero Groth16 proof inside the contract with NEAR's alt_bn128 host functions, and reads the
//! checker's journal. The check is the one tested in spike S6b (verifier/groth16-near), following RISC Zero's own
//! verifier (risc0-groth16 3.0.5 `src/verifier.rs`, risc0-zkvm 3.0.6 `src/claim/receipt.rs`): the claim digest of a
//! normal successful run is computed from the image id and the journal; the five public numbers are the control root
//! and the claim digest (each split into two 128 bit halves) and the BN254 control id; the pairing check is
//! e(-A, B) * e(alpha, beta) * e(vk_x, gamma) * e(C, delta) == 1, with vk_x = IC0 + sum of input_i * IC_i.
//! The fixed values are in `groth16_vk.rs`, generated by scripts/gen_groth16_vk.py.
use near_sdk::env;

#[path = "groth16_vk.rs"]
pub(crate) mod vk;

/// RISC Zero's tagged struct hash (risc0-binfmt 3.0.5 `src/hash.rs`, `tagged_struct`).
fn tagged(tag: &str, down: &[&[u8]], data: &[u32]) -> Vec<u8> {
    let mut all = env::sha256(tag.as_bytes());
    for d in down {
        all.extend_from_slice(d);
    }
    for w in data {
        all.extend_from_slice(&w.to_le_bytes());
    }
    all.extend_from_slice(&(down.len() as u16).to_le_bytes());
    env::sha256(&all)
}

/// Digest of `ReceiptClaim::ok(image_id, journal)`: no input, halted with exit code 0, no assumptions.
fn claim_digest(image_id: &[u8; 32], journal: &[u8]) -> Vec<u8> {
    let zero = [0u8; 32];
    let post = tagged("risc0.SystemState", &[&zero], &[0]);
    let output = tagged("risc0.Output", &[&env::sha256(journal), &zero], &[]);
    tagged("risc0.ReceiptClaim", &[&zero, image_id, &post, &output], &[0, 0])
}

/// One 128 bit half of a digest as a 32 byte little-endian scalar (risc0-groth16 `split_digest`).
fn half(d: &[u8], i: usize) -> [u8; 32] {
    let mut s = [0u8; 32];
    s[..16].copy_from_slice(&d[16 * i..16 * i + 16]);
    s
}

fn rev(b: &[u8]) -> Vec<u8> {
    b.iter().rev().copied().collect()
}

/// True if the 256 byte seal proves that the program with `image_id` ran to a normal end and wrote `journal`.
/// A seal whose numbers are not valid curve points stops the whole call with a host error.
pub fn verify(seal: &[u8], image_id: &[u8; 32], journal: &[u8]) -> bool {
    verify_with_root(seal, image_id, journal, &vk::CONTROL_ROOT)
}

/// `verify` with the control root as a parameter, so a test can show that one changed byte of it fails the check.
pub(crate) fn verify_with_root(seal: &[u8], image_id: &[u8; 32], journal: &[u8], control_root: &[u8; 32]) -> bool {
    if seal.len() != 256 {
        env::panic_str("the Groth16 seal must be 256 bytes");
    }
    let claim = claim_digest(image_id, journal);
    let inputs = [half(control_root, 0), half(control_root, 1), half(&claim, 0), half(&claim, 1), vk::BN254_CONTROL_ID];
    let mut msm = Vec::with_capacity(5 * 96);
    for (i, s) in inputs.iter().enumerate() {
        msm.extend_from_slice(&vk::IC[64 * (i + 1)..64 * (i + 2)]);
        msm.extend_from_slice(s);
    }
    let sum = env::alt_bn128_g1_multiexp(&msm);
    let mut add = vec![0u8];
    add.extend_from_slice(&vk::IC[..64]);
    add.push(0);
    add.extend_from_slice(&sum);
    let vk_x = env::alt_bn128_g1_sum(&add);
    // RISC Zero's seal is big-endian, B with the imaginary part first; NEAR wants little-endian, real part first.
    let a = [rev(&seal[0..32]), rev(&seal[32..64])].concat();
    let b = [rev(&seal[96..128]), rev(&seal[64..96]), rev(&seal[160..192]), rev(&seal[128..160])].concat();
    let c = [rev(&seal[192..224]), rev(&seal[224..256])].concat();
    let mut neg = vec![1u8];
    neg.extend_from_slice(&a);
    let neg_a = env::alt_bn128_g1_sum(&neg);
    let mut pairs = Vec::with_capacity(4 * 192);
    for (p, q) in [(&neg_a[..], &b[..]), (&vk::ALPHA_G1[..], &vk::BETA_G2[..]), (&vk_x[..], &vk::GAMMA_G2[..]), (&c[..], &vk::DELTA_G2[..])] {
        pairs.extend_from_slice(p);
        pairs.extend_from_slice(q);
    }
    env::alt_bn128_pairing_check(&pairs)
}

/// The checker's journal (harness/checker/src/zk.rs `Journal`), committed by the guest with `env::commit`, which
/// writes every field as 32 bit little-endian words and every byte of a `[u8; 32]` as one word: six 32 byte hashes
/// (candidate, original, exploit commitment, corpus, seed, then after the two counts the submission id), the two
/// counts, and the verdict byte. 195 words, 780 bytes.
pub struct Journal {
    pub candidate_hash: [u8; 32],
    pub original_hash: [u8; 32],
    pub exploit_commitment: [u8; 32],
    pub corpus_hash: [u8; 32],
    pub fuzz_seed: [u8; 32],
    pub fuzz_count: u32,
    pub variant_count: u32,
    pub submission_id: [u8; 32],
    pub verdict: u8,
}

pub const JOURNAL_BYTES: usize = 195 * 4;

pub fn parse_journal(j: &[u8]) -> Journal {
    if j.len() != JOURNAL_BYTES {
        env::panic_str("journal is not in the checker's layout (expected 780 bytes)");
    }
    let word = |i: usize| u32::from_le_bytes([j[4 * i], j[4 * i + 1], j[4 * i + 2], j[4 * i + 3]]);
    let byte = |i: usize| -> u8 {
        let w = word(i);
        if w > 255 {
            env::panic_str("journal is not in the checker's layout (a byte word above 255)");
        }
        w as u8
    };
    let hash = |start: usize| -> [u8; 32] { core::array::from_fn(|k| byte(start + k)) };
    let verdict = byte(194);
    if verdict > 1 {
        env::panic_str("journal verdict is neither PASS nor FAIL");
    }
    Journal {
        candidate_hash: hash(0),
        original_hash: hash(32),
        exploit_commitment: hash(64),
        corpus_hash: hash(96),
        fuzz_seed: hash(128),
        fuzz_count: word(160),
        variant_count: word(161),
        submission_id: hash(162),
        verdict,
    }
}
